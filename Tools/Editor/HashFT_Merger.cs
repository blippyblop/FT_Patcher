using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;
#if VRC_SDK
using VRC.SDK3.Avatars.Components;
using VRC.SDK3.Avatars.Models;
#endif

public class HashFT_Merger : EditorWindow
{
    private static bool Debug = false;
    public Object sourceFbx;
    public Object targetFbx;
    public GameObject sourceFtPrefab;
    public GameObject targetPrefab;
    public bool CopyExpressionControllers = false;
    private string statusMessage = "";

    [MenuItem(@"Tools/Hash/FT Merger")]
    public static void ShowWindow()
    {
        HashFT_Merger window = GetWindow<HashFT_Merger>(@"Hash FT_Merger");
        if (!Debug) window.maxSize = new Vector2(460, 360);
        if (Debug) window.maxSize = new Vector2(1000, 700);
        window.Show();
    }

    void OnGUI()
    {
        GUIStyle boldLabelStyle = new GUIStyle(EditorStyles.boldLabel);
        using (new GUILayout.VerticalScope(EditorStyles.helpBox))
        {
            EditorGUILayout.Space(20);
            EditorGUILayout.BeginHorizontal();
            GUILayout.FlexibleSpace();
            GUILayout.Label(@"Hash" + "'s " + @"FT Merger", boldLabelStyle);
            GUILayout.FlexibleSpace();
            EditorGUILayout.EndHorizontal();

            EditorGUILayout.Space(10);
            EditorGUILayout.LabelField("1. Rig: per-muscle settings (eyes etc.)", EditorStyles.boldLabel);
            EditorGUILayout.LabelField("Drag the FBX generated by the FT Patcher (it carries the per-muscle settings in its import settings):", EditorStyles.miniLabel);
            sourceFbx = (Object)EditorGUILayout.ObjectField(sourceFbx, typeof(Object), false);
            EditorGUILayout.LabelField("Drag your custom avatar FBX (target):", EditorStyles.miniLabel);
            targetFbx = (Object)EditorGUILayout.ObjectField(targetFbx, typeof(Object), false);
            if (GUILayout.Button("Apply Rig Settings (source -> target)"))
            {
                ApplyRigSettings();
            }

            EditorGUILayout.Space(10);
            EditorGUILayout.LabelField("2. Prefab: playable layers + expression menu/parameters", EditorStyles.boldLabel);
            sourceFtPrefab = (GameObject)EditorGUILayout.ObjectField("FT Prefab (source, from the package's Prefab folder):", sourceFtPrefab, typeof(GameObject), false);
            targetPrefab = (GameObject)EditorGUILayout.ObjectField("Your avatar Prefab (target):", targetPrefab, typeof(GameObject), false);
            CopyExpressionControllers = EditorGUILayout.Toggle("Also copy expression controllers (will overwrite the target's)", CopyExpressionControllers);
            if (GUILayout.Button("Apply Prefab Settings (source -> target)"))
            {
#if VRC_SDK
                ApplyPrefabSettings();
#else
                statusMessage = "VRC SDK not found: prefab merging is only available in a VRChat Creator Companion project.";
#endif
            }

            EditorGUILayout.Space(10);
            if (!string.IsNullOrEmpty(statusMessage))
            {
                GUILayout.Label(statusMessage, EditorStyles.wordWrappedLabel);
            }
            EditorGUILayout.BeginHorizontal();
            GUILayout.FlexibleSpace();
            if (GUILayout.Button("Documentation", EditorStyles.linkLabel))
            {
                Application.OpenURL("https://hashedits.github.io/docs/");
            }
            GUILayout.FlexibleSpace();
            EditorGUILayout.EndHorizontal();
        }
    }

    private void ApplyRigSettings()
    {
        string srcPath = sourceFbx != null ? AssetDatabase.GetAssetPath(sourceFbx) : "";
        string tgtPath = targetFbx != null ? AssetDatabase.GetAssetPath(targetFbx) : "";
        if (string.IsNullOrEmpty(srcPath) || !srcPath.ToLowerInvariant().EndsWith(".fbx"))
        {
            statusMessage = "Select the patched FT FBX (source).";
            return;
        }
        if (string.IsNullOrEmpty(tgtPath) || !tgtPath.ToLowerInvariant().EndsWith(".fbx"))
        {
            statusMessage = "Select your custom FBX (target).";
            return;
        }

        ModelImporter srcImporter = AssetImporter.GetAtPath(srcPath + ".meta") as ModelImporter;
        ModelImporter tgtImporter = AssetImporter.GetAtPath(tgtPath + ".meta") as ModelImporter;
        if (srcImporter == null || tgtImporter == null)
        {
            statusMessage = "Could not load the FBX importers (are both files imported FBX assets?).";
            return;
        }

        HumanDescription srcHD = srcImporter.humanDescription;
        HumanDescription tgtHD = tgtImporter.humanDescription;
        if (srcHD.human.Length == 0 || tgtHD.human.Length == 0)
        {
            statusMessage = "One of the FBX files has no humanoid bone mapping; per-muscle settings cannot be copied.";
            return;
        }

        int copied = 0;
        int skipped = 0;
        foreach (HumanDescription.Human srcEntry in srcHD.human)
        {
            if (!srcEntry.limit.modified) continue;
            bool matched = false;
            for (int i = 0; i < tgtHD.human.Length; i++)
            {
                if (tgtHD.human[i].humanName == srcEntry.humanName)
                {
                    tgtHD.human[i].limit = srcEntry.limit;
                    copied++;
                    matched = true;
                    if (Debug) UnityEngine.Debug.Log($"[FT Merger] {srcEntry.boneName} ({srcEntry.humanName}) -> {tgtHD.human[i].boneName}");
                    break;
                }
            }
            if (!matched)
            {
                skipped++;
                if (Debug) UnityEngine.Debug.Log($"[FT Merger] skipped {srcEntry.humanName}: not present in target's human mapping");
            }
        }

        if (copied == 0)
        {
            statusMessage = "The source FBX has no customised per-muscle settings to copy (is it the FBX generated by the FT Patcher?).";
            return;
        }

        tgtImporter.humanDescription = tgtHD;
        tgtImporter.SaveAndReimport();
        statusMessage = $"Applied {copied} per-muscle setting(s) from {Path.GetFileName(srcPath)} to {Path.GetFileName(tgtPath)}"
            + (skipped > 0 ? $", {skipped} skipped (no matching bone on the target)" : "")
            + ".";
    }

#if VRC_SDK
    private void ApplyPrefabSettings()
    {
        if (sourceFtPrefab == null || targetPrefab == null)
        {
            statusMessage = "Select both the FT Prefab (source) and your avatar Prefab (target).";
            return;
        }

        string tgtPath = AssetDatabase.GetAssetPath(targetPrefab);
        if (string.IsNullOrEmpty(tgtPath) || !tgtPath.EndsWith(".prefab"))
        {
            statusMessage = "The target must be a Prefab asset (not a scene object).";
            return;
        }

        GameObject sourceRoot = sourceFtPrefab;
        if (PrefabUtility.IsPartOfAnyPrefab(sourceRoot))
        {
            sourceRoot = PrefabUtility.GetCorrespondingObjectFromSource(sourceRoot);
        }
        VRCAvatarDescriptor sourceDesc = sourceRoot.GetComponent<VRCAvatarDescriptor>();
        VRCAvatarPlayables sourcePlayables = sourceRoot.GetComponent<VRCAvatarPlayables>();
        if (sourceDesc == null || sourcePlayables == null)
        {
            statusMessage = "The source prefab has no VRCAvatarDescriptor/Playables (is it the FT prefab from the package?).";
            return;
        }

        GameObject targetContents = PrefabUtility.LoadPrefabContents(tgtPath);
        try
        {
            VRCAvatarDescriptor targetDesc = targetContents.GetComponent<VRCAvatarDescriptor>();
            VRCAvatarPlayables targetPlayables = targetContents.GetComponent<VRCAvatarPlayables>();
            if (targetDesc == null || targetPlayables == null)
            {
                statusMessage = "The target prefab has no VRCAvatarDescriptor/Playables (is it a VRChat avatar prefab?).";
                return;
            }

            int layersTouched = 0;
            foreach (PlayableLayer srcLayer in sourcePlayables.playableLayers)
            {
                if (srcLayer.layerType == PlayableLayerType.Base) continue;

                int index = Array.FindIndex(targetPlayables.playableLayers, layer => layer.layerType == srcLayer.layerType);
                if (index >= 0)
                {
                    PlayableLayer layer = targetPlayables.playableLayers[index];
                    layer.animController = srcLayer.animController;
                    targetPlayables.playableLayers[index] = layer;
                    layersTouched++;
                    if (Debug) UnityEngine.Debug.Log($"[FT Merger] layer {srcLayer.layerType}: controller -> {srcLayer.animController?.name}");
                }
                else
                {
                    List<PlayableLayer> layers = targetPlayables.playableLayers.ToList();
                    layers.Add(new PlayableLayer
                    {
                        layerType = srcLayer.layerType,
                        animController = srcLayer.animController,
                    });
                    targetPlayables.playableLayers = layers.ToArray();
                    layersTouched++;
                    if (Debug) UnityEngine.Debug.Log($"[FT Merger] layer {srcLayer.layerType}: added with controller {srcLayer.animController?.name}");
                }
            }

            if (sourceDesc.baseExpression != null && targetDesc.baseExpression != null)
            {
                targetDesc.baseExpression.menu = sourceDesc.baseExpression.menu;
                targetDesc.baseExpression.parameters = sourceDesc.baseExpression.parameters;
                if (CopyExpressionControllers)
                {
                    targetDesc.baseExpression.controllers = sourceDesc.baseExpression.controllers;
                }
            }

            PrefabUtility.SaveAsPrefabAsset(targetContents, tgtPath);
            statusMessage = $"Applied {layersTouched} playable layer controller(s) and the FT expression menu/parameters to {Path.GetFileName(tgtPath)}"
                + (CopyExpressionControllers ? " (expression controllers overwritten)" : " (existing expression controllers kept)") + ".";
        }
        finally
        {
            PrefabUtility.UnloadPrefabContents(targetContents);
        }
    }
#endif
}